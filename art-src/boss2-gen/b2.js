function feather(g,x0,y0,x1,y1,kfrac){ // 一根羽毛:先畫外框粗線再畫內芯,末端焦黑
 g.L(x0,y0,x1,y1,'O',3);
 const n=Math.max(Math.abs(x1-x0),Math.abs(y1-y0));
 for(let k=0;k<=n;k++){const t=k/n,x=x0+(x1-x0)*t,y=y0+(y1-y0)*t,c=t>kfrac?'K':'W';
   g.S(x+0.5,y+0.5,c);if(t<0.85)g.S(x+0.5,y+1.5,t>kfrac?'K':(t<0.5?'G':c));}
}
